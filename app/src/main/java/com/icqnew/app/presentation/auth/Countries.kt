/** Preferred country for an ambiguous code (+7 → Russia, +1 → USA). */
private val PREFERRED = mapOf("7" to "RU", "1" to "US", "39" to "IT", "262" to "RE", "599" to "CW")

fun countryByIso(iso: String): Country? = COUNTRIES.firstOrNull { it.iso.equals(iso, ignoreCase = true) }

/** Finds the country whose code starts the given number ("+99361234567" → Turkmenistan). */
fun countryForNumber(number: String): Country? {
    val d = number.filter { it.isDigit() }
    if (d.isEmpty()) return null
    for (len in 4 downTo 1) {
        if (d.length < len) continue
        val p = d.substring(0, len)
        val pref = PREFERRED[p]?.let { countryByIso(it) }
        if (pref != null) return pref
        COUNTRIES.firstOrNull { it.dial == p }?.let { return it }
    }
    return null
}
