"""
Database layer for ICQ New.

* No ICQ_DB_URL            -> one server, SQLite file (ICQ_DB), exactly as before.
* ICQ_DB_URL=postgresql:// -> cluster mode: every server of the cluster uses the same PostgreSQL.

server.py is written in SQLite SQL. In PostgreSQL mode the statements are translated on the fly
(placeholders, INSERT OR IGNORE / REPLACE, LIKE, max(a,b), column types, …) and rows behave like
sqlite3.Row (row["col"], row[0], row.keys(), dict(row)), so the rest of the code does not change.
"""
from __future__ import annotations

import os
import queue
import re
import sqlite3
import threading
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

DB_URL = os.environ.get("ICQ_DB_URL", "").strip()
IS_PG = DB_URL.startswith("postgres")

# primary keys of the tables (for INSERT OR REPLACE -> ON CONFLICT … DO UPDATE)
PKS: Dict[str, Tuple[str, ...]] = {
    "users": ("uin",), "tokens": ("token",), "otp": ("phone",), "contacts": ("owner", "contact"),
    "phonebook": ("owner", "key"), "messages": ("id",), "files": ("id",), "meta": ("k",),
    "reactions": ("msg_id", "uin"), "groups": ("id",), "group_members": ("gid", "uin"),
    "blocks": ("owner", "blocked"), "group_bans": ("gid", "uin"), "clears": ("id",),
    "push_tokens": ("token",), "fragment_lots": ("username",), "user_usernames": ("username",),
    "balance_log": ("id",), "user_gifts": ("id",), "chat_ttl": ("a", "b"), "qr_logins": ("code",),
    "link_cache": ("url",), "post_views": ("msg_id", "uin"), "polls": ("msg_id",),
    "poll_votes": ("msg_id", "uin", "opt"), "group_log": ("id",), "stories": ("id",),
    "story_views": ("story", "uin"), "story_comments": ("id",),
    "admins": ("id",), "admin_tokens": ("token",), "admin_log": ("id",), "server_jobs": ("id",),
}
# tables whose id is made by the database (lastrowid)
SERIAL = {"messages", "groups", "clears", "balance_log", "user_gifts", "group_log", "stories", "story_comments",
          "admins", "admin_log", "server_jobs"}


class Row(tuple):
    """Behaves like sqlite3.Row."""

    _names: Tuple[str, ...] = ()

    def __new__(cls, names: Tuple[str, ...], values: Sequence[Any]):
        r = super().__new__(cls, values)
        r._names = names
        return r

    def keys(self) -> List[str]:
        return list(self._names)

    def __getitem__(self, k):  # type: ignore[override]
        if isinstance(k, str):
            try:
                return tuple.__getitem__(self, self._names.index(k))
            except ValueError:
                raise IndexError(f"No item with that key: {k}") from None
        return tuple.__getitem__(self, k)


# ------------------------------------------------------------------ SQL translation (SQLite -> PostgreSQL)
_cache: Dict[str, str] = {}
_cache_lock = threading.Lock()


def _split_outside_quotes(sql: str):
    """Yields (is_code, text) chunks: quoted string literals are kept as they are."""
    i, n, start = 0, len(sql), 0
    while i < n:
        if sql[i] == "'":
            if start < i:
                yield True, sql[start:i]
            j = i + 1
            while j < n:
                if sql[j] == "'":
                    if j + 1 < n and sql[j + 1] == "'":
                        j += 2
                        continue
                    break
                j += 1
            yield False, sql[i:j + 1]
            i = start = j + 1
            continue
        i += 1
    if start < n:
        yield True, sql[start:]


def _two_arg(code: str, fn: str, to: str) -> str:
    """max(a, b) -> GREATEST(a, b) (two arguments; the one-argument MAX(x) stays an aggregate)."""
    out, i = [], 0
    pat = re.compile(r"\b" + fn + r"\s*\(", re.I)
    while True:
        m = pat.search(code, i)
        if not m:
            out.append(code[i:])
            return "".join(out)
        depth, j, comma = 1, m.end(), False
        while j < len(code) and depth:
            ch = code[j]
            if ch == "(":
                depth += 1
            elif ch == ")":
                depth -= 1
            elif ch == "," and depth == 1:
                comma = True
            j += 1
        out.append(code[i:m.start()])
        out.append((to if comma else code[m.start():m.end() - 1].rstrip()) + "(")
        i = m.end()


def _ddl(code: str) -> str:
    code = re.sub(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", code, flags=re.I)
    code = re.sub(r"\bTEXT\s+PRIMARY\s+KEY\s+COLLATE\s+NOCASE\b", "CITEXT PRIMARY KEY", code, flags=re.I)
    code = re.sub(r"\bINTEGER\b", "BIGINT", code, flags=re.I)
    code = re.sub(r"\bBLOB\b", "BYTEA", code, flags=re.I)
    return code


def translate(sql: str) -> str:
    with _cache_lock:
        hit = _cache.get(sql)
    if hit is not None:
        return hit
    s = sql.strip().rstrip(";")
    head = s.lstrip().upper()
    is_ddl = head.startswith("CREATE TABLE") or head.startswith("ALTER TABLE")
    replace_tbl = None
    m = re.match(r"\s*INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*\(([^)]*)\)", s, re.I)
    conflict = ""
    if m:
        kind, tbl, cols = m.group(1).upper(), m.group(2), [c.strip() for c in m.group(3).split(",")]
        s = re.sub(r"^\s*INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO", "INSERT INTO", s, count=1, flags=re.I)
        if kind == "IGNORE":
            conflict = " ON CONFLICT DO NOTHING"
        else:
            pk = PKS.get(tbl.lower(), (cols[0],))
            upd = [c for c in cols if c not in pk]
            conflict = " ON CONFLICT (" + ", ".join(pk) + ") " + (
                "DO UPDATE SET " + ", ".join(f"{c}=EXCLUDED.{c}" for c in upd) if upd else "DO NOTHING")
        replace_tbl = tbl
    parts = []
    for is_code, chunk in _split_outside_quotes(s):
        if not is_code:
            parts.append(chunk.replace("%", "%%"))
            continue
        c = chunk.replace("%", "%%").replace("?", "%s")
        c = re.sub(r"(?<![:\w]):([A-Za-z_]\w*)", r"%(\1)s", c)  # :name -> %(name)s
        c = re.sub(r"(\b[\w.]+)\s*=\s*%s\s+COLLATE\s+NOCASE", r"lower(\1)=lower(%s)", c, flags=re.I)
        c = re.sub(r"\s+COLLATE\s+NOCASE", "", c, flags=re.I) if not is_ddl else c
        c = re.sub(r"\bNOT\s+LIKE\b", "NOT ILIKE", c, flags=re.I)
        c = re.sub(r"(?<!NOT )\bLIKE\b", "ILIKE", c, flags=re.I)
        c = re.sub(r"\bIFNULL\s*\(", "COALESCE(", c, flags=re.I)
        c = _two_arg(c, "max", "GREATEST")
        c = _two_arg(c, "min", "LEAST")
        if is_ddl:
            c = _ddl(c)
        parts.append(c)
    out = "".join(parts)
    if conflict:
        # the conflict clause goes before RETURNING (if any)
        out += conflict
    if head.startswith("INSERT") and replace_tbl is None:
        mm = re.match(r"\s*INSERT\s+INTO\s+(\w+)", out, re.I)
        replace_tbl = mm.group(1) if mm else None
    if head.startswith("INSERT") and replace_tbl and replace_tbl.lower() in SERIAL and " RETURNING " not in out.upper():
        out += " RETURNING id"
    with _cache_lock:
        _cache[sql] = out
    return out


def split_script(script: str) -> List[str]:
    stmts, buf = [], []
    for is_code, chunk in _split_outside_quotes(script):
        if not is_code:
            buf.append(chunk)
            continue
        pieces = chunk.split(";")
        for k, p in enumerate(pieces):
            buf.append(p)
            if k < len(pieces) - 1:
                stmts.append("".join(buf))
                buf = []
    stmts.append("".join(buf))
    return [x.strip() for x in stmts if x.strip()]


# ------------------------------------------------------------------ PostgreSQL connection wrapper
class _Cursor:
    def __init__(self, cur, lastrowid=None) -> None:
        self._cur = cur
        self.lastrowid = lastrowid
        self.rowcount = cur.rowcount if cur is not None else 0
        self._buffered: Optional[List[Row]] = None

    def _names(self) -> Tuple[str, ...]:
        return tuple(d.name for d in (self._cur.description or ()))

    def fetchone(self) -> Optional[Row]:
        if self._buffered is not None:
            return self._buffered.pop(0) if self._buffered else None
        if self._cur is None or self._cur.description is None:
            return None
        r = self._cur.fetchone()
        return Row(self._names(), r) if r is not None else None

    def fetchall(self) -> List[Row]:
        if self._buffered is not None:
            out, self._buffered = self._buffered, []
            return out
        if self._cur is None or self._cur.description is None:
            return []
        names = self._names()
        return [Row(names, r) for r in self._cur.fetchall()]

    def __iter__(self):
        return iter(self.fetchall())


def _params(p):
    if p is None:
        return None
    if isinstance(p, dict):
        return {k: int(v) if isinstance(v, bool) else v for k, v in p.items()}
    out = []
    for v in p:
        if isinstance(v, bool):
            v = int(v)
        out.append(v)
    return tuple(out)


class PgConn:
    def __init__(self, raw) -> None:
        self.raw = raw
        self.row_factory = None  # compatibility

    # sqlite3 style: commit on success, roll back on an exception
    def __enter__(self) -> "PgConn":
        return self

    def __exit__(self, et, ev, tb) -> bool:
        try:
            if et is None:
                self.raw.commit()
            else:
                self.raw.rollback()
        finally:
            _pool_put(self.raw)
            self.raw = None
        return False

    def execute(self, sql: str, params: Optional[Iterable] = None) -> _Cursor:
        q = translate(sql)
        p = _params(params) if params is not None else None
        if p is not None and len(p) == 0:
            p = None
        if p is None:
            q = q.replace("%%", "%")
        cur = self.raw.cursor()
        is_insert = q.lstrip()[:6].upper() == "INSERT"
        if is_insert:
            # a failed INSERT must not spoil the whole transaction (sqlite code catches IntegrityError and goes on)
            cur.execute("SAVEPOINT icq_sp")
        try:
            cur.execute(q, p)
        except Exception as e:  # noqa: BLE001
            if is_insert:
                cur.execute("ROLLBACK TO SAVEPOINT icq_sp")
            raise _map_error(e) from e
        lastrowid = None
        if is_insert and " RETURNING id" in q and cur.description is not None:
            rows = cur.fetchall()
            lastrowid = rows[0][0] if rows else None
            res = _Cursor(cur, lastrowid)
            res._buffered = [Row(("id",), r) for r in rows]
            res.rowcount = len(rows)
        else:
            res = _Cursor(cur, lastrowid)
        if is_insert:
            cur.execute("RELEASE SAVEPOINT icq_sp")
        return res

    def executemany(self, sql: str, seq) -> None:
        for p in seq:
            self.execute(sql, p)

    def executescript(self, script: str) -> None:
        for st in split_script(script):
            up = st.upper()
            if up.startswith("PRAGMA"):
                continue
            self.execute(st)

    def commit(self) -> None:
        self.raw.commit()

    def close(self) -> None:
        if self.raw is not None:
            self.raw.rollback()
            _pool_put(self.raw)
            self.raw = None


def _map_error(e: Exception) -> Exception:
    try:
        import psycopg
        if isinstance(e, psycopg.errors.IntegrityError):
            return sqlite3.IntegrityError(str(e))
        if isinstance(e, psycopg.Error):
            return sqlite3.OperationalError(str(e))
    except ImportError:
        pass
    return e


_pool: "queue.LifoQueue" = queue.LifoQueue()
_POOL_MAX = int(os.environ.get("ICQ_DB_POOL", "16"))


def _new_raw():
    import psycopg
    return psycopg.connect(DB_URL, autocommit=False, connect_timeout=10)


def _pool_get():
    while True:
        try:
            raw = _pool.get_nowait()
        except queue.Empty:
            return _new_raw()
        if not raw.closed and raw.info.transaction_status == 0:  # IDLE
            return raw
        try:
            raw.close()
        except Exception:  # noqa: BLE001
            pass


def _pool_put(raw) -> None:
    if raw is None or raw.closed:
        return
    if _pool.qsize() >= _POOL_MAX:
        raw.close()
        return
    try:
        if raw.info.transaction_status != 0:
            raw.rollback()
    except Exception:  # noqa: BLE001
        raw.close()
        return
    _pool.put(raw)


# ------------------------------------------------------------------ public API used by server.py
def connect(sqlite_path: str):
    if IS_PG:
        return PgConn(_pool_get())
    c = sqlite3.connect(sqlite_path, timeout=15)
    c.row_factory = sqlite3.Row
    return c


def add_column(c, table: str, ddl: str) -> None:
    if IS_PG:
        c.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {ddl}")
        return
    name = ddl.split()[0]
    cols = {r["name"] for r in c.execute(f"PRAGMA table_info({table})").fetchall()}
    if name not in cols:
        c.execute(f"ALTER TABLE {table} ADD COLUMN {ddl}")


def prepare() -> None:
    """PostgreSQL: the case-insensitive text type used for @names."""
    if not IS_PG:
        return
    raw = _new_raw()
    try:
        raw.execute("CREATE EXTENSION IF NOT EXISTS citext")
        raw.commit()
    except Exception as e:  # noqa: BLE001
        raw.rollback()
        print("[db] citext:", e, flush=True)
    finally:
        raw.close()


def advisory_lock(c, key: int) -> None:
    """Serialises a schema change between servers that start at the same time."""
    if IS_PG:
        c.execute("SELECT pg_advisory_xact_lock(?)", (key,))
